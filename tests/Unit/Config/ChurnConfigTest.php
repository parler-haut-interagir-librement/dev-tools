<?php

declare(strict_types=1);

namespace Phil\DevTools\Tests\Unit\Config;

use Phil\DevTools\Config\ChurnConfig;
use Phil\DevTools\Exception\InvalidManifest;
use Phil\DevTools\Tests\Unit\Support\TemporaryDirectory;
use Phil\DevTools\Workspace\Workspace;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\TestWith;
use PHPUnit\Framework\TestCase;

#[CoversClass(ChurnConfig::class)]
final class ChurnConfigTest extends TestCase
{
    use TemporaryDirectory;

    public function testTheDefaults(): void
    {
        $root = $this->root('<?php return [];');

        self::assertSame(<<<YAML
            # Generated by phil-dev from the composer.json and phil-dev.php of each package. Do not edit.
            directoriesToScan:
              - '{$root}/src'
            filesToShow: 10
            commitsSince: 'One year ago'
            fileExtensions:
              - 'php'
            vcs: 'git'
            cachePath: '{$root}/var/phil-dev/churn.cache'

            YAML, new ChurnConfig(Workspace::load($root))->yaml());
    }

    public function testTheRootManifest(): void
    {
        $config = new ChurnConfig(Workspace::load($this->root("<?php return ['hotspots' => ['files' => 1, 'since' => '6 months ago']];")))->build();

        self::assertSame(1, $config['filesToShow']);
        self::assertSame('6 months ago', $config['commitsSince']);
    }

    #[TestWith(["['files' => 0]", 'hotspots.files must be a positive integer.'])]
    #[TestWith(["['files' => '10']", 'hotspots.files must be a positive integer.'])]
    #[TestWith(["['since' => 6]", 'hotspots.since must be a date git understands, such as "6 months ago".'])]
    public function testAnInvalidManifest(string $hotspots, string $message): void
    {
        $workspace = Workspace::load($this->root("<?php return ['hotspots' => ".$hotspots.'];'));

        $this->expectException(InvalidManifest::class);
        $this->expectExceptionMessageIsOrContains($message);

        new ChurnConfig($workspace)->build();
    }

    private function root(string $manifest): string
    {
        $root = $this->temporaryDirectory();
        $this->put($root.'/composer.json', '{"name": "phil/x", "autoload": {"psr-4": {"Phil\\\\X\\\\": "src/"}}}');
        $this->put($root.'/phil-dev.php', $manifest);
        mkdir($root.'/src');

        return $root;
    }
}
