<?php

declare(strict_types=1);

namespace Phil\DevTools\Tests\Unit\Config;

use Phil\DevTools\Config\PsalmConfig;
use Phil\DevTools\Exception\InvalidManifest;
use Phil\DevTools\Tests\Unit\Support\TemporaryDirectory;
use Phil\DevTools\Workspace\Workspace;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

#[CoversClass(PsalmConfig::class)]
final class PsalmConfigTest extends TestCase
{
    use TemporaryDirectory;

    public function testTheSourceDirectoriesOfAPackage(): void
    {
        $root = $this->temporaryDirectory();
        $this->put($root.'/composer.json', '{"name": "phil/x", "autoload": {"psr-4": {"Phil\\\\X\\\\": "src/"}}}');
        mkdir($root.'/src');

        $expected = <<<XML
            <?xml version="1.0"?>
            <!-- Generated by phil-dev from the composer.json and phil-dev.php of each package. Do not edit. -->
            <psalm xmlns="https://getpsalm.org/schema/config"
                   xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
                   xsi:schemaLocation="https://getpsalm.org/schema/config {$root}/vendor-bin/psalm/vendor/vimeo/psalm/config.xsd"
                   errorLevel="8"
                   phpVersion="8.5"
                   autoloader="{$root}/vendor/autoload.php"
                   cacheDirectory="{$root}/var/phil-dev/psalm"
                   findUnusedCode="false"
                   findUnusedBaselineEntry="false"
            >
                <projectFiles>
                    <directory name="{$root}/src" />
                    <ignoreFiles allowMissingFiles="true">
                        <directory name="{$root}/vendor" />
                        <directory name="{$root}/var" />
                    </ignoreFiles>
                </projectFiles>
            </psalm>

            XML;

        self::assertSame($expected, new PsalmConfig(Workspace::load($root))->xml());
    }

    public function testTheExcludesAndSuppressionsOfEveryMember(): void
    {
        $root = $this->fixture('monorepo');
        $this->put($root.'/packages/slug/phil-dev.php', "<?php return ['psalm' => ['excludes' => ['src/Generated', 'src/Generated'], 'suppress' => ['TaintedHtml' => ['src/Raw.php', 'src/View', 'src/Raw.php']]]];");
        $this->put($root.'/packages/slug/src/Raw.php', '<?php');
        $this->put($root.'/packages/slug-bundle/phil-dev.php', "<?php return ['psalm' => ['suppress' => ['TaintedHtml' => ['src/Raw.php'], 'TaintedSql' => ['src/Query.php']]]];");

        $xml = new PsalmConfig(Workspace::load($root))->xml();
        $slug = $root.'/packages/slug';

        self::assertStringContainsString("            <directory name=\"{$root}/var\" />\n            <directory name=\"{$slug}/src/Generated\" />\n        </ignoreFiles>", $xml);
        self::assertStringContainsString(
            "    <issueHandlers>\n        <TaintedHtml>\n            <errorLevel type=\"suppress\">\n"
            ."                <file name=\"{$slug}/src/Raw.php\" />\n"
            ."                <directory name=\"{$slug}/src/View\" />\n"
            ."                <directory name=\"{$root}/packages/slug-bundle/src/Raw.php\" />\n"
            ."            </errorLevel>\n        </TaintedHtml>\n        <TaintedSql>\n",
            $xml,
        );
        self::assertStringEndsWith("        </TaintedSql>\n    </issueHandlers>\n</psalm>\n", $xml);
    }

    public function testPathsAreEscaped(): void
    {
        $root = $this->temporaryDirectory().'/a&b"c';
        mkdir($root);
        $this->put($root.'/composer.json', '{"name": "phil/x"}');

        self::assertStringContainsString('autoloader="'.\dirname($root).'/a&amp;b&quot;c/vendor/autoload.php"', new PsalmConfig(Workspace::load($root))->xml());
    }

    /**
     * @return iterable<string, array{string, string}>
     */
    public static function invalidSuppressions(): iterable
    {
        yield 'a list' => ["['src/X.php']", 'psalm.suppress of phil/x maps an issue type, such as TaintedHtml, to a list of paths.'];
        yield 'an issue type in lower case' => ["['taintedHtml' => ['src/X.php']]", 'psalm.suppress of phil/x maps an issue type, such as TaintedHtml, to a list of paths.'];
        yield 'an issue type that is not a word' => ["['Tainted Html' => ['src/X.php']]", 'psalm.suppress of phil/x maps an issue type, such as TaintedHtml, to a list of paths.'];
        yield 'a path alone' => ["['TaintedHtml' => 'src/X.php']", 'psalm.suppress of phil/x maps an issue type, such as TaintedHtml, to a list of paths.'];
        yield 'something else than a path' => ["['TaintedHtml' => [1]]", 'psalm.suppress.TaintedHtml of phil/x must list paths.'];
    }

    #[DataProvider('invalidSuppressions')]
    public function testAnInvalidSuppression(string $suppress, string $message): void
    {
        $root = $this->temporaryDirectory();
        $this->put($root.'/composer.json', '{"name": "phil/x"}');
        $this->put($root.'/phil-dev.php', "<?php return ['psalm' => ['suppress' => ".$suppress.']];');

        $this->expectException(InvalidManifest::class);
        $this->expectExceptionMessageIsOrContains($message);

        new PsalmConfig(Workspace::load($root))->xml();
    }
}
