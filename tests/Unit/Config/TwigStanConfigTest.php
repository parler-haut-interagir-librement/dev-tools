<?php

declare(strict_types=1);

namespace Phil\DevTools\Tests\Unit\Config;

use Phil\DevTools\Config\TwigStanConfig;
use Phil\DevTools\DevTools;
use Phil\DevTools\Exception\InvalidManifest;
use Phil\DevTools\Tests\Unit\Support\TemporaryDirectory;
use Phil\DevTools\Workspace\Workspace;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\TestCase;

#[CoversClass(TwigStanConfig::class)]
final class TwigStanConfigTest extends TestCase
{
    use TemporaryDirectory;

    public function testTheConfiguration(): void
    {
        $root = $this->root('<?php return [];');
        $config = new TwigStanConfig(Workspace::load($root));

        self::assertSame(DevTools::directory().'/config/twig-loader.php', $config->loader());
        self::assertSame(<<<PHP
            <?php

            // Generated by phil-dev from the composer.json and phil-dev.php of each package. Do not edit.

            return TwigStan\\Config\\TwigStanConfig::configure('{$root}')
                ->tempDirectory('{$root}/var/phil-dev/twigstan')
                ->phpstanConfigurationFile('/x/twigstan.neon')
                ->twigEnvironmentLoader('{$config->loader()}')
                ->twigPaths('{$root}/templates')
                ->phpPaths('{$root}/src')
                ->create();

            PHP, $config->php('/x/twigstan.neon'));
        self::assertSame("# Generated by phil-dev. Do not edit.\nparameters:\n    level: max\n    tmpDir: {$root}/var/phil-dev/twigstan-phpstan\n    bootstrapFiles:\n        - {$root}/vendor/autoload.php\n", $config->neon());
        self::assertSame(['PHIL_DEV_TWIG_PATHS' => '["'.$root.'/templates"]'], $config->environment());
    }

    public function testTheLoaderOfAPackageAndQuotesEscaped(): void
    {
        $root = $this->root("<?php return ['twig' => ['loader' => 'tests/twig-loader.php']];");

        $config = new TwigStanConfig(Workspace::load($root));

        self::assertSame($root.'/tests/twig-loader.php', $config->loader());
        self::assertStringContainsString("->phpstanConfigurationFile('/it\\'s\\\\here.neon')", $config->php("/it's\\here.neon"));
    }

    public function testTheLoaderOfAMember(): void
    {
        $root = $this->fixture('monorepo');
        $this->put($root.'/packages/tilttek-dice/phil-dev.php', "<?php return ['twig' => ['loader' => 'loader.php']];");

        self::assertSame($root.'/packages/tilttek-dice/loader.php', new TwigStanConfig(Workspace::load($root))->loader());
    }

    public function testALoaderThatIsNotAPath(): void
    {
        $root = $this->root("<?php return ['twig' => ['loader' => ['x']]];");

        $this->expectException(InvalidManifest::class);
        $this->expectExceptionMessageIsOrContains('twig.loader of phil/x must be the path of a PHP file.');

        new TwigStanConfig(Workspace::load($root))->loader();
    }

    private function root(string $manifest): string
    {
        $root = $this->temporaryDirectory();
        $this->put($root.'/composer.json', '{"name": "phil/x", "autoload": {"psr-4": {"Phil\\\\X\\\\": "src/"}}}');
        $this->put($root.'/phil-dev.php', $manifest);
        mkdir($root.'/src');
        mkdir($root.'/templates');

        return $root;
    }
}
