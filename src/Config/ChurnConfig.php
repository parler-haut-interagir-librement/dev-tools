<?php

declare(strict_types=1);

namespace Phil\DevTools\Config;

use Phil\DevTools\Exception\InvalidManifest;
use Phil\DevTools\Workspace\Workspace;

/**
 * The churn-php configuration of a workspace: the production code of every package analysed, ranked by how often a
 * file changes and how complex it is. The root's `hotspots.files` and `hotspots.since` change how many files are
 * shown, ten by default, and how far back the history is read, one year by default.
 */
final readonly class ChurnConfig
{
    public function __construct(private Workspace $workspace)
    {
    }

    /**
     * @return array<string, mixed>
     */
    public function build(): array
    {
        $manifest = $this->workspace->root->manifest;
        $files = $manifest->get('hotspots', 'files') ?? 10;
        $since = $manifest->get('hotspots', 'since') ?? 'One year ago';

        if (!\is_int($files) || $files < 1) {
            throw new InvalidManifest('hotspots.files must be a positive integer.');
        }

        if (!\is_string($since)) {
            throw new InvalidManifest('hotspots.since must be a date git understands, such as "6 months ago".');
        }

        return [
            'directoriesToScan' => new Tooling($this->workspace)->sourceDirectories(),
            'filesToShow' => $files,
            'commitsSince' => $since,
            'fileExtensions' => ['php'],
            'vcs' => 'git',
            'cachePath' => $this->workspace->root->path('var/phil-dev/churn.cache'),
        ];
    }

    public function yaml(): string
    {
        return YamlWriter::write($this->build(), 'Generated by phil-dev from the composer.json and phil-dev.php of each package. Do not edit.');
    }
}
