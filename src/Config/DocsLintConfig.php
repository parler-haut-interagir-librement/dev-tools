<?php

declare(strict_types=1);

namespace Phil\DevTools\Config;

use JsonException;
use Phil\DevTools\DevTools;
use Phil\DevTools\Exception\InvalidManifest;
use Phil\DevTools\Workspace\Package;
use Phil\DevTools\Workspace\Workspace;

/**
 * The configurations of the prose linters of the documentation: cspell for the spelling, markdownlint for the
 * Markdown, Vale for the style.
 *
 * A package's documentation is in English unless its manifest says `docs.language: 'fr'`, as the French corpora do:
 * cspell then reads the French dictionary as well, and Vale, whose rules here are written for English, leaves it out.
 * The words of the root's and the package's `docs.words` are added to the shared list of `resources/docs/words.txt`.
 */
final readonly class DocsLintConfig
{
    /** @var list<string> */
    public const array LANGUAGES = ['en', 'fr'];

    /**
     * The Markdown files of a package the linters read, besides those under `doc/`.
     *
     * @var list<string>
     */
    public const array ROOT_FILES = ['README.md', 'CHANGELOG.md', 'CONTRIBUTING.md', 'SECURITY.md'];

    public function __construct(private Workspace $workspace)
    {
    }

    public function language(Package $package): string
    {
        $language = $package->manifest->get('docs', 'language') ?? $this->workspace->root->manifest->get('docs', 'language') ?? 'en';

        if (!\is_string($language) || !\in_array($language, self::LANGUAGES, true)) {
            throw new InvalidManifest(\sprintf('docs.language of %s is one of %s.', $package->name, implode(', ', self::LANGUAGES)));
        }

        return $language;
    }

    /**
     * The Markdown files of the package, absolute: those of `ROOT_FILES` that exist, and every `.md` under `doc/`.
     *
     * @return list<string>
     */
    public function files(Package $package): array
    {
        $files = array_values(array_filter(array_map($package->path(...), self::ROOT_FILES), is_file(...)));
        $doc = $package->directory('doc');

        if (null !== $doc) {
            $found = glob($doc.'/{,*/}*.md', \GLOB_BRACE);
            array_push($files, ...(false === $found ? [] : $found));
        }

        return $files;
    }

    public function cspell(Package $package): string
    {
        $words = [
            ...$this->workspace->root->manifest->strings('docs', 'words'),
            ...($package->isRoot() ? [] : $package->manifest->strings('docs', 'words')),
        ];
        $french = 'fr' === $this->language($package);

        return $this->json(array_filter([
            'version' => '0.2',
            // The documentation writes British spellings as well as American ones: licence, analyse.
            'language' => $french ? 'fr,en,en-GB' : 'en,en-GB',
            'import' => $french ? ['@cspell/dict-fr-fr/cspell-ext.json'] : null,
            'dictionaryDefinitions' => [['name' => 'phil', 'path' => DevTools::resource('docs/words.txt'), 'addWords' => false]],
            'dictionaries' => ['phil'],
            'words' => array_values(array_unique($words)),
            'ignoreRegExpList' => ['/```[\s\S]*?```/g', '/`[^`\n]+`/g', '/\]\([^)]*\)/g'],
        ], static fn (mixed $value): bool => null !== $value));
    }

    /**
     * The markdownlint rules: the defaults, lines of 120 columns outside code and tables, headings repeated only in
     * other sections, compact table separators, and the root's `docs.markdownlint` over them.
     */
    public function markdownlint(): string
    {
        $config = InfectionConfig::merge([
            'default' => true,
            'MD013' => ['line_length' => 120, 'code_blocks' => false, 'tables' => false],
            'MD024' => ['siblings_only' => true],
            // The tables separate their header with |---|, without the spaces this rule asks for.
            'MD060' => false,
        ], $this->workspace->root->manifest->map('docs', 'markdownlint'));

        return $this->json(['config' => $config]);
    }

    public function vale(): string
    {
        return implode("\n", [
            '# Generated by phil-dev. Do not edit.',
            'StylesPath = '.DevTools::resource('docs/vale'),
            'MinAlertLevel = warning',
            '',
            '[*.md]',
            'BasedOnStyles = Vale, Phil',
            '# cspell checks the spelling, with the words of each package.',
            'Vale.Spelling = NO',
            '',
        ]);
    }

    /**
     * @param array<string, mixed> $data
     */
    private function json(array $data): string
    {
        try {
            return json_encode($data, \JSON_PRETTY_PRINT | \JSON_UNESCAPED_SLASHES | \JSON_UNESCAPED_UNICODE | \JSON_THROW_ON_ERROR)."\n";
        } catch (JsonException $jsonException) {
            throw new InvalidManifest('The docs section cannot be written as JSON: '.$jsonException->getMessage(), $jsonException->getCode(), previous: $jsonException);
        }
    }
}
