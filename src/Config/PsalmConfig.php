<?php

declare(strict_types=1);

namespace Phil\DevTools\Config;

use Phil\DevTools\Exception\InvalidManifest;
use Phil\DevTools\Matrix\Matrix;
use Phil\DevTools\Workspace\Workspace;

/**
 * The Psalm configuration of a workspace, generated for its taint analysis: PHPStan stays the analyser of the gates,
 * and Psalm only follows what comes from a request, a file or the environment to where it must not arrive unescaped —
 * HTML, SQL, a shell, a file path, an `unserialize()`.
 *
 * It covers the production code of every package analysed, without the tests. Each manifest adds its
 * `psalm.excludes`, paths left out, and its `psalm.suppress`, an issue type with the paths where it is a known and
 * reviewed exception.
 */
final readonly class PsalmConfig
{
    public function __construct(private Workspace $workspace)
    {
    }

    public function xml(): string
    {
        $root = $this->workspace->root;
        $tooling = new Tooling($this->workspace);
        $directories = [];
        $ignores = [$root->path('vendor'), $root->path('var')];
        $suppressions = [];

        foreach ($tooling->sourceDirectories() as $directory) {
            $directories[] = '        <directory name="'.self::escape($directory).'" />';
        }

        foreach ($this->workspace->analysed() as $package) {
            foreach ($package->manifest->strings('psalm', 'excludes') as $exclude) {
                $ignores[] = $package->path($exclude);
            }

            foreach ($package->manifest->map('psalm', 'suppress') as $issue => $paths) {
                if (!\is_string($issue) || 1 !== preg_match('/^[A-Z][A-Za-z]+$/', $issue) || !\is_array($paths)) {
                    throw new InvalidManifest(\sprintf('psalm.suppress of %s maps an issue type, such as TaintedHtml, to a list of paths.', $package->name));
                }

                foreach ($paths as $path) {
                    if (!\is_string($path)) {
                        throw new InvalidManifest(\sprintf('psalm.suppress.%s of %s must list paths.', $issue, $package->name));
                    }

                    $suppressions[$issue][] = $package->path($path);
                }
            }
        }

        $xml = [
            '<?xml version="1.0"?>',
            '<!-- Generated by phil-dev from the composer.json and phil-dev.php of each package. Do not edit. -->',
            '<psalm xmlns="https://getpsalm.org/schema/config"',
            '       xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
            '       xsi:schemaLocation="https://getpsalm.org/schema/config '.self::escape($root->path('vendor-bin/psalm/vendor/vimeo/psalm/config.xsd')).'"',
            '       errorLevel="8"',
            '       phpVersion="'.Matrix::load()->floor('php')->version.'"',
            '       autoloader="'.self::escape($root->path('vendor/autoload.php')).'"',
            '       cacheDirectory="'.self::escape($root->path('var/phil-dev/psalm')).'"',
            '       findUnusedCode="false"',
            '       findUnusedBaselineEntry="false"',
            '>',
            '    <projectFiles>',
            ...$directories,
            '        <ignoreFiles allowMissingFiles="true">',
            ...array_map(static fn (string $path): string => '            '.self::entry($path), array_unique($ignores)),
            '        </ignoreFiles>',
            '    </projectFiles>',
        ];

        if ([] !== $suppressions) {
            $xml[] = '    <issueHandlers>';

            foreach ($suppressions as $issue => $paths) {
                $xml[] = '        <'.$issue.'>';
                $xml[] = '            <errorLevel type="suppress">';

                foreach (array_unique($paths) as $path) {
                    $xml[] = '                '.self::entry($path);
                }

                $xml[] = '            </errorLevel>';
                $xml[] = '        </'.$issue.'>';
            }

            $xml[] = '    </issueHandlers>';
        }

        $xml[] = '</psalm>';

        return implode("\n", $xml)."\n";
    }

    /**
     * A `<file>` for a path that is a file, a `<directory>` for anything else.
     */
    private static function entry(string $path): string
    {
        return \sprintf('<%s name="%s" />', is_file($path) ? 'file' : 'directory', self::escape($path));
    }

    private static function escape(string $value): string
    {
        return htmlspecialchars($value, \ENT_XML1 | \ENT_QUOTES);
    }
}
