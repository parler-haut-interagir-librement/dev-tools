<?php

declare(strict_types=1);

namespace Phil\DevTools\Config;

use JsonException;
use Phil\DevTools\DevTools;
use Phil\DevTools\Exception\InvalidManifest;
use Phil\DevTools\Workspace\Workspace;

/**
 * The TwigStan configuration of a workspace: the templates and the PHP code that renders them, of every package
 * analysed, and the PHPStan configuration TwigStan analyses the compiled templates with.
 *
 * TwigStan runs its own PHPStan from `vendor-bin/twig/`, which has none of the extensions of `vendor-bin/phpstan/`: it
 * gets a configuration of its own, at the maximum level, with the autoloader of the project.
 */
final readonly class TwigStanConfig
{
    /**
     * The variable the shared Twig loader reads the template directories from, as a JSON list.
     */
    public const string PATHS_VARIABLE = 'PHIL_DEV_TWIG_PATHS';

    public function __construct(private Workspace $workspace)
    {
    }

    /**
     * The file a package names under `twig.loader`, which returns its `Twig\Environment`, else the shared one, which
     * loads the templates from their directories.
     */
    public function loader(): string
    {
        foreach ($this->workspace->analysed() as $package) {
            $loader = $package->manifest->get('twig', 'loader');

            if (null === $loader) {
                continue;
            }

            if (!\is_string($loader)) {
                throw new InvalidManifest(\sprintf('twig.loader of %s must be the path of a PHP file.', $package->name));
            }

            return $package->path($loader);
        }

        return DevTools::directory().'/config/twig-loader.php';
    }

    public function php(string $neon): string
    {
        $tooling = new Tooling($this->workspace);
        $root = $this->workspace->root;
        $lines = [
            '<?php',
            '',
            '// Generated by phil-dev from the composer.json and phil-dev.php of each package. Do not edit.',
            '',
            'return TwigStan\Config\TwigStanConfig::configure('.$this->export($root->dir).')',
            '    ->tempDirectory('.$this->export($root->path('var/phil-dev/twigstan')).')',
            '    ->phpstanConfigurationFile('.$this->export($neon).')',
            '    ->twigEnvironmentLoader('.$this->export($this->loader()).')',
            '    ->twigPaths('.implode(', ', array_map($this->export(...), $tooling->templateDirectories())).')',
            '    ->phpPaths('.implode(', ', array_map($this->export(...), $tooling->sourceDirectories())).')',
            '    ->create();',
        ];

        return implode("\n", $lines)."\n";
    }

    public function neon(): string
    {
        $root = $this->workspace->root;

        return "# Generated by phil-dev. Do not edit.\nparameters:\n    level: max\n    tmpDir: "
            .$root->path('var/phil-dev/twigstan-phpstan')."\n    bootstrapFiles:\n        - ".$root->path('vendor/autoload.php')."\n";
    }

    /**
     * The template directories, as the shared loader reads them from `PHIL_DEV_TWIG_PATHS`.
     *
     * @return array<string, string>
     */
    public function environment(): array
    {
        try {
            return [self::PATHS_VARIABLE => json_encode(new Tooling($this->workspace)->templateDirectories(), \JSON_UNESCAPED_SLASHES | \JSON_THROW_ON_ERROR)];
        } catch (JsonException $jsonException) {
            throw new InvalidManifest('The template directories cannot be written as JSON: '.$jsonException->getMessage(), $jsonException->getCode(), previous: $jsonException);
        }
    }

    private function export(string $value): string
    {
        return "'".addcslashes($value, "'\\")."'";
    }
}
